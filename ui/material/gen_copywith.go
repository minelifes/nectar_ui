//go:build ignore

// gen_copywith writes copywith_gen.go: a CopyWith method for every theme
// and style type of the package (XxxTheme, XxxStyle, ColorScheme).
//
//	go generate ./ui/material
package main

import (
	"bytes"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"log"
	"os"
	"slices"
	"strings"
	"text/template"
)

func main() {
	names, err := themeTypes(".")
	if err != nil {
		log.Fatal(err)
	}
	var b bytes.Buffer
	if err := tmpl.Execute(&b, names); err != nil {
		log.Fatal(err)
	}
	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("copywith_gen.go", src, 0o644); err != nil {
		log.Fatal(err)
	}
}

// themeTypes lists the exported struct types named …Theme / …Style and
// ColorScheme, sorted.
func themeTypes(dir string) ([]string, error) {
	fset := token.NewFileSet()
	pkgs, err := parser.ParseDir(fset, dir, func(fi os.FileInfo) bool {
		return !strings.HasSuffix(fi.Name(), "_test.go")
	}, 0)
	if err != nil {
		return nil, err
	}
	var names []string
	for _, p := range pkgs {
		for _, f := range p.Files {
			for _, d := range f.Decls {
				g, ok := d.(*ast.GenDecl)
				if !ok {
					continue
				}
				for _, s := range g.Specs {
					ts, ok := s.(*ast.TypeSpec)
					if !ok || !ts.Name.IsExported() {
						continue
					}
					if _, ok := ts.Type.(*ast.StructType); !ok {
						continue
					}
					n := ts.Name.Name
					if strings.HasSuffix(n, "Theme") || strings.HasSuffix(n, "Style") || n == "ColorScheme" {
						names = append(names, n)
					}
				}
			}
		}
	}
	slices.Sort(names)
	return names, nil
}

var tmpl = template.Must(template.New("").Parse(`// Code generated by gen_copywith.go; DO NOT EDIT.

package material
{{range .}}
// CopyWith returns a copy of t with the fields set in over replacing t's
// (see "How component themes and styles work" in theme_style.go).
func (t {{.}}) CopyWith(over {{.}}) {{.}} { return merge(t, over) }
{{end}}`))
